# Таймауты генерации скриншотов (в секундах).
# Все три значения должны оставаться согласованными:
#   WATCHDOG < ZOMBIE < FRONTEND_POLL
# Иначе фронтенд перестанет опрашивать до того, как сервер поставит финальный статус.

# Защитный таймер в фоновом потоке: принудительно завершает генерацию если
# она не завершилась сама за это время.
SCREENSHOT_WATCHDOG_TIMEOUT = 15 * 60  # 15 минут

# Зомби-восстановление в generation_status_api: если генерация stuck в processing
# (сервер перезапустили, daemon-поток умер), переводим в failed.
SCREENSHOT_ZOMBIE_TIMEOUT = 20 * 60  # 20 минут

# Таймаут опроса на фронтенде (мс). Должен быть больше SCREENSHOT_ZOMBIE_TIMEOUT,
# чтобы фронтенд не прекратил опрос раньше, чем сервер выдаст финальный статус.
FRONTEND_POLL_TIMEOUT_MS = 22 * 60 * 1000  # 22 минуты
