def _make_project(tmp_path, pkg: dict, lock_files: dict | None = None) -> Path:
    root = tmp_path / 'project'
    root.mkdir()
    (root / 'package.json').write_text(json.dumps(pkg), encoding='utf-8')
    for name, content in (lock_files or {}).items():
        (root / name).write_text(content, encoding='utf-8')
    return root


