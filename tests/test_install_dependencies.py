# ---------------------------------------------------------------------------
# Нет прямых print() в фоновой ветке (take_route_screenshots / take_nx_screenshots)
# ---------------------------------------------------------------------------

def test_no_bare_print_in_screenshot_service():
    """
    take_route_screenshots и take_nx_screenshots не должны вызывать print()
    с flush=True — это блокирует консоль Windows в Quick Edit Mode.
    Проверяем AST исходника.
    """
    import core.services.screenshot_service as svc_module
    source = inspect.getsource(svc_module)
    tree = ast.parse(source)

    # Собираем все вызовы print(..., flush=True) в функциях фонового пути
    bg_functions = {'take_route_screenshots', 'take_nx_screenshots'}
    violations = []

    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef):
            continue
        if node.name not in bg_functions:
            continue
        for child in ast.walk(node):
            if not isinstance(child, ast.Call):
                continue
            func = child.func
            if not (isinstance(func, ast.Name) and func.id == 'print'):
                continue
            # Есть keyword flush=True?
            for kw in child.keywords:
                if kw.arg == 'flush' and isinstance(kw.value, ast.Constant) and kw.value.value:
                    violations.append(f"{node.name}: строка {child.lineno}")

    assert not violations, (
        f"Найдены print(flush=True) в фоновом пути: {violations}. "
        f"Используй _log() вместо print."
    )


# ---------------------------------------------------------------------------
# Нет прямых print() в core/views.py
# ---------------------------------------------------------------------------

def test_no_print_in_views():
    """
    core/views.py не должен содержать вызовов print() — они блокируют
    консоль Windows (Quick Edit Mode) при любом выводе в cmd.
    Весь вывод должен идти через logging.
    """
    import core.views as views_module
    source = inspect.getsource(views_module)
    tree = ast.parse(source)

    violations = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Name) and func.id == 'print':
                violations.append(f"строка {node.lineno}")

    assert not violations, (
        f"Найдены вызовы print() в core/views.py: {violations}. "
        f"Используй logging вместо print."
    )
